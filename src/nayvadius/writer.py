def write_vocabulary_from_db(db, root):
    root = Path(root) / "vocabulary"
    root.mkdir(parents=True, exist_ok=True)
    rows = list(db.execute(
        "SELECT id,word,traditional,pinyin,pos,meaning_ko,hsk_levels,wordbooks,source FROM vocabularies ORDER BY word"
    ))
    for vid, word, traditional, pinyin, pos, meaning_ko, hsk_levels, wordbooks, source in rows:
        out = root / (safe(vid) + ".md")
        levels = [x for x in (hsk_levels or "").split("|") if x]
        books = [x for x in (wordbooks or "").split("|") if x]
        links = list(db.execute(
            "SELECT entity_name,entity_type FROM entity_vocabulary_links WHERE vocabulary_id=? ORDER BY entity_name",
            (vid,)
        ))
        entity_lines = "\n".join(f"- [[{name}]] ({etype})" for name, etype in links) or "- None"
        text = (
            "---\n"
            "id: " + yaml_scalar(vid) + "\n"
            "word: " + yaml_scalar(word) + "\n"
            "traditional: " + yaml_scalar(traditional) + "\n"
            "pinyin: " + yaml_scalar(pinyin) + "\n"
            "pos: " + yaml_scalar(pos) + "\n"
            "source: " + yaml_scalar(source) + "\n"
            "hsk_levels: [" + ", ".join(yaml_scalar(x) for x in levels) + "]\n"
            "wordbooks: [" + ", ".join(yaml_scalar(x) for x in books) + "]\n"
            "---\n\n"
            "# " + word + "\n\n"
            "## Meaning\n" + (meaning_ko or "- None") + "\n\n"
            "## Linked entities\n" + entity_lines + "\n\n"
            "## Mentioned in\n"
            + (("\n".join("- [[" + title + "]]" for title, in db.execute("SELECT d.title FROM document_vocabulary_links l JOIN documents d ON d.id=l.document_id WHERE l.vocabulary_id=? ORDER BY d.title", (vid,)).fetchall())) or "- None")
            + "\n"
        )
        write_atomic(out, text)


def write_vocabulary_moc(db, root):
    root = Path(root) / "vocabulary"
    root.mkdir(parents=True, exist_ok=True)
    rows = list(db.execute(
        "SELECT id,word,pinyin,hsk_levels,wordbooks FROM vocabularies ORDER BY word"
    ))
    lines = ["---", "title: \"Vocabulary Index\"", "type: \"MOC\"", "---", "", "# Vocabulary Index", ""]
    for vid, word, pinyin, hsk_levels, wordbooks in rows:
        levels = ", ".join(x for x in (hsk_levels or "").split("|") if x) or "unclassified"
        lines.append(f"- [[{word}]] — {pinyin or '-'} — {levels}")
    write_atomic(root / "_Vocabulary Index.md", "\n".join(lines) + "\n")


def write_hsk_mocs(db, root):
    root = Path(root) / "vocabulary"
    groups = [("HSK6", {"6"}), ("HSK7-9", {"7", "8", "9", "7-9"})]
    for label, wanted in groups:
        rows = []
        for row in db.execute("SELECT word,pinyin,hsk_levels FROM vocabularies ORDER BY word"):
            levels = set(x for x in (row[2] or "").split("|") if x)
            if levels & wanted:
                rows.append(row)
        folder = root / label
        folder.mkdir(parents=True, exist_ok=True)
        lines = ["---", f'title: "{label} Vocabulary"', 'type: "MOC"', "---", "", f"# {label} Vocabulary", ""]
        lines.extend(f"- [[{word}]] — {pinyin or '-'}" for word, pinyin, _ in rows)
        write_atomic(folder / "_Index.md", "\n".join(lines) + "\n")
